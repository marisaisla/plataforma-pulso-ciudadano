BEGIN;
CREATE TABLE IF NOT EXISTS field_questionnaires (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        task_id BIGINT NOT NULL REFERENCES territorial_action_plans(id),
        title TEXT NOT NULL, description TEXT NOT NULL, definition TEXT NOT NULL,
        mode TEXT NOT NULL CHECK(mode IN ('single','multiple')),
        status TEXT NOT NULL CHECK(status IN ('draft','published')),
        created_by BIGINT NOT NULL REFERENCES field_workers(id),
        created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'));
CREATE TABLE IF NOT EXISTS field_task_surveys (
        task_id BIGINT PRIMARY KEY REFERENCES territorial_action_plans(id),
        questionnaire_id BIGINT NOT NULL REFERENCES field_questionnaires(id),
        generation TEXT NOT NULL, target BIGINT NOT NULL CHECK(target > 0));
CREATE TABLE IF NOT EXISTS field_survey_responses (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        task_id BIGINT NOT NULL REFERENCES territorial_action_plans(id),
        questionnaire_id BIGINT NOT NULL REFERENCES field_questionnaires(id),
        worker_id BIGINT NOT NULL REFERENCES field_workers(id),
        assignment_generation TEXT NOT NULL, survey_generation TEXT NOT NULL,
        submission_key TEXT NOT NULL UNIQUE, answers TEXT NOT NULL,
        profile_id BIGINT NOT NULL REFERENCES profiles(id), state TEXT NOT NULL, municipality TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'));
CREATE INDEX IF NOT EXISTS field_survey_response_task_idx ON field_survey_responses(task_id, questionnaire_id);
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='go2win_owner') THEN
        ALTER TABLE field_questionnaires OWNER TO go2win_owner;
        ALTER TABLE field_task_surveys OWNER TO go2win_owner;
        ALTER TABLE field_survey_responses OWNER TO go2win_owner;
    END IF;
END $$;
COMMIT;
